#!/usr/bin/env node
/**
 * Is package-lock.json complete for EVERY platform, not just this one?
 *
 * Why this exists
 * ---------------
 * The container is built on `node:22-alpine` (musl). CI installs on the
 * runner's glibc image. npm resolves a different set of optional platform
 * packages on each, so a lockfile can be perfectly valid where CI runs it and
 * still break `docker build`.
 *
 * That is not hypothetical — it is what happened. npm/cli#8320 leaves
 * platform-specific optional dependencies out of the lockfile when it is
 * generated on a different OS. `@img/sharp-wasm32` and
 * `@tailwindcss/oxide-wasm32-wasi` both want `@emnapi/core` and
 * `@emnapi/runtime` at ^1.11.1; neither was written. `npm ci` passed on
 * Windows and on the glibc runner, and failed only inside Alpine, where the
 * Dockerfile's fallback quietly regenerated the lockfile in-image — which
 * defeats the reproducibility `npm ci` exists to provide.
 *
 * Worse, the fix does not stay fixed on its own: running `npm install` on
 * Windows rewrites the entries straight back out. So this check is the durable
 * half, not the regeneration.
 *
 * What it does
 * ------------
 * Walks every package in the lockfile and resolves each of its declared
 * dependencies the way Node does — nearest `node_modules` first, then up the
 * tree. Anything unresolvable is exactly what `npm ci` would reject, on
 * whichever platform happens to need it.
 *
 * Deliberately dependency-free and platform-independent: no Docker, no network.
 * A gate that needs docker-in-docker inside a containerised runner is a gate
 * that goes red for environmental reasons, and those get ignored (L-5).
 *
 *   node scripts/verify-lockfile.mjs
 */
import { readFileSync } from "node:fs";

const lock = JSON.parse(readFileSync(new URL("../package-lock.json", import.meta.url), "utf8"));
const packages = lock.packages ?? {};

/** Resolve `dep` from `fromPath` the way Node does: nearest node_modules up. */
function resolves(fromPath, dep) {
  // "node_modules/a/node_modules/b" -> try b's own, then a's, then root.
  let prefix = fromPath;
  for (;;) {
    if (packages[`${prefix ? prefix + "/" : ""}node_modules/${dep}`]) return true;
    const cut = prefix.lastIndexOf("/node_modules/");
    if (cut === -1) break;
    prefix = prefix.slice(0, cut);
  }
  return Boolean(packages[`node_modules/${dep}`]);
}

const missing = [];
for (const [path, meta] of Object.entries(packages)) {
  if (meta.link) continue; // workspace symlink, resolved elsewhere
  // peerDependencies are intentionally excluded: npm may legitimately leave an
  // unmet optional peer out of the tree, and `npm ci` does not fail on it.
  const deps = { ...(meta.dependencies ?? {}), ...(meta.optionalDependencies ?? {}) };
  for (const dep of Object.keys(deps)) {
    if (!resolves(path, dep)) {
      missing.push({ from: path || "(root)", dep, range: deps[dep] });
    }
  }
}

if (missing.length === 0) {
  console.log(`✓ package-lock.json is complete — ${Object.keys(packages).length} packages, every dependency resolves`);
  process.exit(0);
}

console.error(`✗ package-lock.json is INCOMPLETE — ${missing.length} unresolvable dependenc${missing.length === 1 ? "y" : "ies"}:\n`);
for (const m of missing.slice(0, 25)) {
  console.error(`  ${m.dep}@${m.range}`);
  console.error(`      required by ${m.from}`);
}
if (missing.length > 25) console.error(`  … and ${missing.length - 25} more`);
console.error(`
This breaks \`npm ci\` on whichever platform needs those packages — most likely
the node:22-alpine image that builds the container, even while CI stays green.

Fix: regenerate the lockfile on Linux, NOT on Windows or macOS —

    docker run --rm -v "\$PWD":/w -w /w node:22-alpine \\
      npm install --package-lock-only --ignore-scripts

then re-run this check. Do not commit a lockfile regenerated by a plain
\`npm install\` on Windows: it drops these entries again (npm/cli#8320).
`);
process.exit(1);
